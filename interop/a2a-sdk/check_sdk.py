"""Interop check: the unmodified A2A Python SDK against a MAP provider.

Checks, against a running `map-a2a-provider` (default http://127.0.0.1:8702):
  1. the SDK resolves and parses our Agent Card;
  2. the SDK's own signature verifier (a2a.utils.signing, PyJWT, EdDSA)
     accepts the card's JWS under the AgentID key named by `kid`. The SDK
     canonicalizes the card independently (proto MessageToDict + empty-value
     removal + sorted-key JSON), so this is a cross-implementation check of
     the payload rule, not a self-check;
  3. negative control: the same verifier REJECTS the card once one field is
     altered, so check 2 is not vacuous;
  4. a plain SendMessage (no MAP extension) returns a COMPLETED task with the
     full artifact and no MAP metadata (binding A2A-28), and GetTask agrees;
  5. offline: the committed test vector TV-022 (a signed card generated by
     spec/test-vectors/gen_vectors.py) verifies under the same SDK verifier.

Usage:  python interop/a2a-sdk/check_sdk.py [base-url]
Requires: pip install -r interop/a2a-sdk/requirements.txt
Exit 0 iff every check passes.
"""

import asyncio
import base64
import json
import pathlib
import re
import sys

import base58
import httpx
from a2a.client import A2ACardResolver, ClientConfig, create_client
from a2a.types import a2a_pb2 as pb
from a2a.utils.signing import create_signature_verifier
from google.protobuf.json_format import ParseDict
from jwt.api_jwk import PyJWK

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8702"
results = []


def check(name, ok, detail=""):
    results.append(ok)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f" -- {detail}" if detail and not ok else ""))


def key_for(kid, _jku):
    # kid is the AgentID in multibase form: 'z' + base58btc(0xed 0x01 || pk).
    raw = base58.b58decode(kid[1:])
    assert kid[0] == "z" and raw[:2] == b"\xed\x01" and len(raw) == 34, "not an Ed25519 AgentID"
    x = base64.urlsafe_b64encode(raw[2:]).rstrip(b"=").decode()
    return PyJWK({"kty": "OKP", "crv": "Ed25519", "x": x})


def tv022_card():
    md = pathlib.Path(__file__).resolve().parents[2] / "spec" / "test-vectors" / "map-test-vectors.md"
    sec = md.read_text(encoding="utf-8").split("## TV-022", 1)[1]
    line = next(l for l in sec.splitlines() if re.match(r"^\{.*\}\s*$", l))
    return ParseDict(json.loads(line), pb.AgentCard(), ignore_unknown_fields=False)


async def main():
    verify = create_signature_verifier(key_for, ["EdDSA"])
    try:
        verify(tv022_card())
        check("TV-022 (generated signed card) verifies under the SDK verifier", True)
    except Exception as e:  # noqa: BLE001
        check("TV-022 (generated signed card) verifies under the SDK verifier", False, repr(e))
    async with httpx.AsyncClient() as http:
        card = await A2ACardResolver(http, BASE).get_agent_card()
    check("SDK resolves and parses the Agent Card", card.name != "", card.name)

    try:
        verify(card)
        check("SDK verifier accepts the card's EdDSA JWS", True)
    except Exception as e:  # noqa: BLE001
        check("SDK verifier accepts the card's EdDSA JWS", False, repr(e))

    tampered = pb.AgentCard()
    tampered.CopyFrom(card)
    tampered.description = card.description + " (altered)"
    try:
        verify(tampered)
        check("negative control: altered card is rejected", False, "verifier accepted a modified card")
    except Exception:  # noqa: BLE001
        check("negative control: altered card is rejected", True)

    client = await create_client(card, client_config=ClientConfig(streaming=False))
    req = pb.SendMessageRequest(
        message=pb.Message(message_id="sdk-1", role=pb.ROLE_USER, parts=[pb.Part(text="Write a short status report")])
    )
    task = None
    async for resp in client.send_message(req):
        if resp.HasField("task"):
            task = resp.task
    ok = task is not None and task.status.state == pb.TASK_STATE_COMPLETED
    check("plain SendMessage returns a COMPLETED task", ok, str(task.status.state if task else None))
    if task is not None:
        n = sum(len(a.parts) for a in task.artifacts)
        check("artifact carries every Part", n > 0, str(n))
        check("no MAP metadata for a client that did not activate the extension", "map/v2" not in task.metadata)
        got = await client.get_task(pb.GetTaskRequest(id=task.id))
        check("GetTask returns the same completed task", got.id == task.id and got.status.state == pb.TASK_STATE_COMPLETED)
    await client.close()


asyncio.run(main())
print("ALL PASS" if all(results) else "FAILED")
sys.exit(0 if all(results) else 1)
